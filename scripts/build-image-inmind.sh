#!/usr/bin/env bash
# build-image-inmind.sh — build the AntiFox runtime image from the current checkout (inmind fork), the way
# upstream's release CI does it, without a local Go/Node toolchain (containers):
#   1. web static export (web/.env.production → English default; version shown in the UI = $VERSION) node:22
#   2. Go binary with the web UI and skills embedded, linux/amd64   golang (version from go.mod)
#   3. docker build (upstream Dockerfile: tools + Playwright/Chromium + the binary)
# Version = git describe + "-inmind": not a clean semver, so the in-app one-click update stays disabled
# (it would replace the fork with upstream's release).
#   scripts/build-image-inmind.sh [image-name]      default image name: antifox
set -euo pipefail
cd "$(dirname "$0")/.."
NAME="${1:-antifox}"
[[ -z "$(git status --porcelain --untracked-files=no)" ]] || { echo "working tree has changes — commit first" >&2; exit 1; }
VERSION="$(git describe --tags --always)-inmind"
GO_VERSION="$(awk '/^go /{print $2}' go.mod)"
U="$(id -u):$(id -g)"
echo "== $NAME:$VERSION (go $GO_VERSION)"

echo "== 1/3 web"
docker run --rm -u "$U" -e HOME=/tmp -e npm_config_cache=/tmp/npm -v "$PWD/web:/web" -w /web node:22-bookworm \
  -e V="${VERSION#v}" sh -c 'npm ci --no-audit --no-fund --loglevel=error && rm -rf out .next \
    && npm version "$V" --no-git-tag-version --allow-same-version >/dev/null && npm run build:static >/dev/null'
git checkout -- web/package.json web/package-lock.json   # version stamp is for this build only (as upstream CI)
rm -rf server/webui/dist server/skillsdist && mkdir -p server/webui/dist server/skillsdist
cp -r web/out/. server/webui/dist/
cp -r skills/. server/skillsdist/ && rm -rf server/skillsdist/report-generation   # generated by the Go side (as upstream CI)

echo "== 2/3 binary"
mkdir -p dist/amd64
docker run --rm -u "$U" -e HOME=/tmp -e GOCACHE=/tmp/gocache -e GOPATH=/tmp/gopath -e CGO_ENABLED=0 -e GOOS=linux -e GOARCH=amd64 \
  -v "$PWD:/src" -w /src "golang:$GO_VERSION" \
  go build -tags embedui -trimpath -ldflags "-s -w -X main.version=$VERSION" -o dist/amd64/antifox ./cmd/antifox
rm -rf server/webui/dist server/skillsdist

echo "== 3/3 image"
docker build --build-arg TARGETARCH=amd64 \
  --label org.opencontainers.image.source=https://github.com/cstephan-dev/antifox \
  --label org.opencontainers.image.revision="$(git rev-parse HEAD)" \
  --label org.opencontainers.image.version="$VERSION" \
  -t "$NAME:$VERSION" .
rm -rf dist   # not in upstream's .gitignore
echo "== built $NAME:$VERSION"
